from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
from rdkit import Chem


DEFAULT_OUTPUT_DIR = Path("runs/generation_compare_50_20261002/new_pdb")
DEFAULT_ORDINALS = (3, 10, 23)


def _element_from_atom_name(atom_name: str) -> str:
    letters = "".join(char for char in str(atom_name).strip() if char.isalpha())
    if not letters:
        return "C"
    # Protein cache atom names use standard PDB names; CA is carbon, not calcium.
    return letters[0].upper()


def _format_atom(
    record_type: str,
    serial: int,
    atom_name: str,
    residue_name: str,
    chain_id: str,
    residue_id: int,
    xyz: np.ndarray,
    element: str,
) -> str:
    atom_name = str(atom_name).strip()[:4]
    element = str(element).strip().upper()[:2]
    return (
        f"{record_type:<6}{serial:5d} {atom_name:>4s} "
        f"{residue_name:>3s} {chain_id:1s}{residue_id:4d}    "
        f"{float(xyz[0]):8.3f}{float(xyz[1]):8.3f}{float(xyz[2]):8.3f}"
        f"{1.00:6.2f}{0.00:6.2f}          {element:>2s}\n"
    )


def _load_source(source_path: Path) -> dict[str, np.ndarray]:
    with np.load(source_path, allow_pickle=False) as source:
        return {key: source[key] for key in source.files}


def _write_ligand_pdb(path: Path, molecule: Chem.Mol, title: str) -> None:
    conformer = molecule.GetConformer()
    lines = [f"REMARK  Generated by TargetDiff APLC model: {title}\n"]
    for index, atom in enumerate(molecule.GetAtoms(), start=1):
        point = conformer.GetAtomPosition(index - 1)
        xyz = np.asarray([point.x, point.y, point.z], dtype=np.float64)
        lines.append(
            _format_atom(
                "HETATM",
                index,
                f"{atom.GetSymbol()}{index}",
                "LIG",
                "Z",
                1,
                xyz,
                atom.GetSymbol(),
            )
        )
    lines.extend(_conect_lines(molecule, serial_offset=0))
    lines.append("END\n")
    path.write_text("".join(lines))


def _conect_lines(molecule: Chem.Mol, serial_offset: int) -> list[str]:
    lines = []
    for bond in molecule.GetBonds():
        begin = serial_offset + bond.GetBeginAtomIdx() + 1
        end = serial_offset + bond.GetEndAtomIdx() + 1
        lines.append(f"CONECT{begin:5d}{end:5d}\n")
        lines.append(f"CONECT{end:5d}{begin:5d}\n")
    return lines


def _write_complex_pdb(
    path: Path,
    molecule: Chem.Mol,
    source: dict[str, np.ndarray],
    title: str,
) -> None:
    protein_pos = np.asarray(source["protein_pos"], dtype=np.float64)
    atom_names = np.asarray(source["protein_atom_name"])
    residue_names = np.asarray(source["protein_residue_name"])
    residue_indices = np.asarray(source["protein_residue_index"], dtype=np.int64)
    if not (
        protein_pos.shape[0]
        == atom_names.shape[0]
        == residue_names.shape[0]
        == residue_indices.shape[0]
    ):
        raise ValueError("Protein source fields have inconsistent atom counts")

    conformer = molecule.GetConformer()
    lines = [
        f"REMARK  Generated by TargetDiff APLC model: {title}\n",
        "REMARK  Protein chain IDs are synthetic because the prepared cache omits them.\n",
        "REMARK  Protein coordinates are the apo pocket input; ligand is generated.\n",
    ]
    serial = 1
    for atom_name, residue_name, residue_index, xyz in zip(
        atom_names, residue_names, residue_indices, protein_pos
    ):
        lines.append(
            _format_atom(
                "ATOM",
                serial,
                str(atom_name),
                str(residue_name),
                "A",
                int(residue_index),
                xyz,
                _element_from_atom_name(str(atom_name)),
            )
        )
        serial += 1

    ligand_serial_offset = serial - 1
    for index, atom in enumerate(molecule.GetAtoms(), start=1):
        point = conformer.GetAtomPosition(index - 1)
        xyz = np.asarray([point.x, point.y, point.z], dtype=np.float64)
        lines.append(
            _format_atom(
                "HETATM",
                ligand_serial_offset + index,
                f"{atom.GetSymbol()}{index}",
                "LIG",
                "Z",
                1,
                xyz,
                atom.GetSymbol(),
            )
        )
    lines.extend(_conect_lines(molecule, serial_offset=ligand_serial_offset))
    lines.append("END\n")
    path.write_text("".join(lines))


def export_sample(
    output_dir: Path,
    source_root: Path,
    ordinal: int,
) -> dict[str, object]:
    sample_json = output_dir.parent / "new" / f"sample_{ordinal:03d}.json"
    if not sample_json.is_file():
        raise FileNotFoundError(sample_json)
    record = json.loads(sample_json.read_text())
    pair_json = output_dir.parent / "pairs" / f"pair_{ordinal:03d}.json"
    if not pair_json.is_file():
        raise FileNotFoundError(pair_json)
    pair_record = json.loads(pair_json.read_text())
    metrics = record.get("metrics", {})
    if metrics.get("connected") is not True:
        raise ValueError(f"Sample {ordinal} is not a connected reconstructed molecule")
    sdf_path = output_dir.parent / "new" / f"sample_{ordinal:03d}.sdf"
    if not sdf_path.is_file():
        raise FileNotFoundError(sdf_path)
    source_path = source_root / pair_record["source_sample_path"]
    if not source_path.is_file():
        raise FileNotFoundError(source_path)

    molecule = Chem.MolFromMolFile(str(sdf_path), removeHs=False, sanitize=True)
    if molecule is None:
        raise ValueError(f"RDKit could not read {sdf_path}")
    source = _load_source(source_path)
    stem = f"sample_{ordinal:03d}_{record['pdb_id']}"
    ligand_path = output_dir / f"{stem}_ligand.pdb"
    complex_path = output_dir / f"{stem}_apo_pocket_complex.pdb"
    title = (
        f"{stem}; trajectory={record['trajectory_id']}; "
        f"QED={metrics.get('qed')}; SA={metrics.get('sa')}"
    )
    _write_ligand_pdb(ligand_path, molecule, title)
    _write_complex_pdb(complex_path, molecule, source, title)
    return {
        "ordinal": ordinal,
        "pdb_id": record["pdb_id"],
        "trajectory_id": record["trajectory_id"],
        "smiles": metrics.get("smiles"),
        "qed": metrics.get("qed"),
        "sa": metrics.get("sa"),
        "ligand_pdb": str(ligand_path),
        "complex_pdb": str(complex_path),
    }


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Export selected APLC TargetDiff generated molecules as PDB files."
    )
    parser.add_argument("--source-root", type=Path, default=Path("."))
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    parser.add_argument(
        "--ordinals",
        type=int,
        nargs="+",
        default=list(DEFAULT_ORDINALS),
        help="Sample ordinals from the 50-pair generation run.",
    )
    args = parser.parse_args()

    source_root = args.source_root.resolve()
    output_dir = args.output_dir
    if not output_dir.is_absolute():
        output_dir = source_root / output_dir
    output_dir.mkdir(parents=True, exist_ok=True)
    exported = [
        export_sample(output_dir, source_root, ordinal)
        for ordinal in args.ordinals
    ]
    manifest_path = output_dir / "export_manifest.json"
    manifest_path.write_text(json.dumps(exported, indent=2) + "\n")
    print(json.dumps(exported, indent=2))
    print(f"Manifest: {manifest_path}")


if __name__ == "__main__":
    main()
